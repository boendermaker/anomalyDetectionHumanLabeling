import fs from 'node:fs';
const root = process.argv[2];
const data = JSON.parse(fs.readFileSync(`${root}/example-iot-data.json`,'utf8'));
let maxV=-1,idx=-1;
data.forEach((r,i)=>{const v=r.values?.bearing_temp_c; if(v&&typeof v==='object'&&v.value>maxV){maxV=v.value;idx=i;}});
data[idx].values.bearing_temp_c.humanLabel='anomaly';
const res = await fetch('http://localhost:3000/train',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({data,selectedIndices:[idx],timeSteps:10})});
const t = await res.json();
console.log('labeledAnomalyRecords:', t.labeledAnomalyRecords);
console.log('normalRecords:', t.normalRecords, 'anomalyRecords:', t.anomalyRecords);
console.log('threshold:', t.anomalyThreshold);
const p = await fetch('http://localhost:3000/predict',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(data)});
const pr = await p.json();
console.log('predicted threshold:', pr.threshold);
const win = pr.predictions.find(x=>x.recordIndices.includes(idx));
console.log('spike window', idx, 'mse=', win?.mse, 'isAnomaly=', win?.isAnomaly);
console.log('spike channelMse:', win?.channelMse);
